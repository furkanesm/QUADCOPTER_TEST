import numpy as np

k = 2.6269644483e-5
g = 0.00980665

table = [
    (1, 270, 2900),
    (2, 380, 3548),
    (3, 470, 4095),
    (4, 580, 4450),
    (5, 640, 4671),
    (6, 720, 4970),
    (7, 790, 5185),
    (8, 860, 5400),
    (9, 920, 5588),
    (10, 980, 5735),
    (12, 1100, 6077),
    (14, 1190, 6325),
    (16, 1250, 6565),
    (19.7, 1370, 6874)
]

print("RPM  | Tablo (gf) | Formül (gf) | Hata (%)")
print("------------------------------------------")
for (A, gf, rpm) in table:
    omega = rpm * 2 * np.pi / 60
    F_N = k * (omega**2)
    F_gf = F_N / g
    err = abs(F_gf - gf) / gf * 100
    print(f"{rpm:<4} | {gf:<10} | {F_gf:<11.1f} | {err:.2f}%")

